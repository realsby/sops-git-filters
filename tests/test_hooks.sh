#!/usr/bin/env bash
# The permission hooks: which git commands they cover (audit L1), and
# where install.sh writes them and where it does not (audit N8).
# shellcheck disable=SC2154  # OUT/RC/TOOL/AGE_* come from tests/lib.sh

# ── Commands that write a secret again (audit L1) ────
# Before, only post-checkout and post-merge existed: a rebase, a
# cherry-pick, a revert, an amend, `git am` and the first commit of a new
# secret left the file at the umask mode (0644).
test_hooks_keep_0600_after_everyday_commands() {
	umask 022
	new_repo repo
	local hooks name
	hooks="$(git rev-parse --git-path hooks)"
	for name in post-checkout post-merge post-rewrite post-applypatch post-commit; do
		assert_contains "$(cat "${hooks}/${name}")" 'managed by sops-git-filters' "${name} hook"
	done

	# A new secret is 0644 until its first commit.
	printf 'A=1\n' >.env
	git add .env
	git commit -q -m "base"
	assert_eq "$(mode_of .env)" "600" "mode after the first commit of a new secret"

	git checkout -q -b feature
	printf 'A=2\n' >.env
	git commit -q -am "feature: change the secret"
	git checkout -q main
	printf 'x\n' >other.txt
	git add other.txt
	git commit -q -m "main: something else"

	git checkout -q feature
	chmod 644 .env
	git rebase -q main
	assert_eq "$(cat .env)" "A=2" "working copy after the rebase"
	assert_eq "$(mode_of .env)" "600" "mode after git rebase"

	git checkout -q main
	chmod 644 .env
	git cherry-pick feature >/dev/null
	assert_eq "$(cat .env)" "A=2" "working copy after the cherry-pick"
	assert_eq "$(mode_of .env)" "600" "mode after git cherry-pick"

	chmod 644 .env
	git revert --no-edit HEAD >/dev/null
	assert_eq "$(cat .env)" "A=1" "working copy after the revert"
	assert_eq "$(mode_of .env)" "600" "mode after git revert"

	printf 'A=3\n' >.env
	git commit -q -am "change the secret again"
	chmod 644 .env
	git commit -q --amend -m "the same change, reworded"
	assert_eq "$(mode_of .env)" "600" "mode after git commit --amend"

	git format-patch -1 --stdout >../change.patch
	git checkout -q -b am-target HEAD~1
	chmod 644 .env
	git am -q ../change.patch
	assert_eq "$(cat .env)" "A=3" "working copy after git am"
	assert_eq "$(mode_of .env)" "600" "mode after git am"

	assert_eq "$(git status --porcelain)" "" "git status"
}

# ── A hooks directory shared with other repositories (audit N8) ────
# With a machine-wide core.hooksPath, install.sh wrote its hooks into
# that directory. They ran in EVERY repository of the user and called
# "$root"/utilities/sops-git-filters/harden-permissions.sh there: cloning
# any repository that ships a file at that path executed it.

# shared_hooks_home : a HOME and a global git config of this test's own,
# with core.hooksPath pointing at a directory in that HOME. Sets SHARED.
shared_hooks_home() {
	export HOME="${PWD}/home"
	mkdir -p "${HOME}/.githooks"
	cp "${GIT_CONFIG_GLOBAL}" "${PWD}/gitconfig"
	export GIT_CONFIG_GLOBAL="${PWD}/gitconfig"
	# With the tilde: git expands it, and install.sh must do the same.
	# shellcheck disable=SC2088  # the tilde is meant to reach git as it is
	git config --global core.hooksPath '~/.githooks'
	SHARED="${HOME}/.githooks"
}

# plain_repo <dir> : a repository with the tool and a managed .env
# pattern, install.sh not run yet; cd into it
plain_repo() {
	git init -q "$1"
	cd "$1" || exit 1
	vendor_tool
	# shellcheck disable=SC2119  # no extra recipients here
	write_sops_yaml
	printf '.env filter=sops diff=sops\n' >.gitattributes
	git add -A
	git commit -q -m scaffold
}

# hostile_repo <dir> : a repository that ships a script at the path the
# hooks call. When it runs, the file PWNED appears next to <dir>.
hostile_repo() {
	local marker="${PWD}/PWNED"
	git init -q "$1"
	mkdir -p "$1/${TOOL}"
	printf '#!/bin/sh\ntouch %s\n' "${marker}" >"$1/${TOOL}/harden-permissions.sh"
	chmod +x "$1/${TOOL}/harden-permissions.sh"
	git -C "$1" add -A
	git -C "$1" commit -q -m "looks harmless"
}

# old_hook <hook name> <the HARDEN line> : the hook file as install.sh
# wrote it from v1.1.0 to v2.0.0, byte for byte
old_hook() {
	cat <<EOF_HOOK
#!/usr/bin/env bash
# managed by sops-git-filters (secret file permissions)
#
# $1: git cannot store mode 0600, so a checkout or merge that
# re-runs the SOPS smudge filter recreates secrets with the caller's
# umask (0644 by default). Re-tighten every filter=sops file.
#
# Generated by install.sh — edit harden-permissions.sh, not this file.
# Delete it to opt out; re-running install.sh restores it.
set -u
root="\$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0
$2
[ -x "\${HARDEN}" ] || exit 0
"\${HARDEN}" --root "\${root}" --quiet || true
exit 0
EOF_HOOK
}

test_hooks_are_not_written_into_a_shared_directory() {
	shared_hooks_home
	plain_repo repo
	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	assert_contains "${OUT}" "not write there" "install.sh says it left the shared directory alone"
	assert_eq "$(ls -A "${SHARED}")" "" "files in the shared hooks directory"
	assert_eq "$(git config --local --get filter.sops.required)" "true" "the filters are configured all the same"
	cd ..

	# Nothing of a cloned repository runs.
	hostile_repo hostile
	git clone -q hostile victim
	[[ ! -e PWNED ]] || fail "cloning a repository ran its harden-permissions.sh"
}

test_hooks_of_an_earlier_install_are_removed_from_a_shared_directory() {
	shared_hooks_home
	# What v2.0.0 wrote there (post-checkout), what a later development
	# version wrote (post-merge), a hook someone built on top of it
	# (post-applypatch, which nothing below triggers: it is left in place
	# and would still run), and two hooks that have nothing to do with
	# this tool.
	# shellcheck disable=SC2016  # $root belongs to the hook
	old_hook post-checkout 'HARDEN="$root/'"${TOOL}"'/harden-permissions.sh"' >"${SHARED}/post-checkout"
	# shellcheck disable=SC2016
	old_hook post-merge 'HARDEN="$root"/'"${TOOL}"'/harden-permissions.sh' >"${SHARED}/post-merge"
	{
		# shellcheck disable=SC2016
		old_hook post-applypatch 'HARDEN="$root/'"${TOOL}"'/harden-permissions.sh"'
		echo 'echo "my own addition"'
	} >"${SHARED}/post-applypatch"
	printf '#!/bin/sh\necho "my own pre-push"\n' >"${SHARED}/pre-push"
	printf '#!/bin/sh\n# calls sops-git-filters by hand\necho "my own post-rewrite"\n' >"${SHARED}/post-rewrite"
	chmod +x "${SHARED}"/*
	cp "${SHARED}/post-applypatch" post-applypatch.before

	plain_repo repo
	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	[[ ! -e "${SHARED}/post-checkout" ]] || fail "the post-checkout hook of v2.0.0 is still in the shared directory"
	[[ ! -e "${SHARED}/post-merge" ]] || fail "the post-merge hook is still in the shared directory"
	assert_contains "${OUT}" "Removed ${SHARED}/post-checkout" "install.sh output"
	assert_contains "${OUT}" "Removed ${SHARED}/post-merge" "install.sh output"
	# Everything else is as it was.
	cmp "${SHARED}/post-applypatch" ../post-applypatch.before || fail "a hook that was changed by hand was touched"
	assert_contains "${OUT}" "${SHARED}/post-applypatch carries the sops-git-filters marker" "install.sh names the changed hook"
	assert_contains "$(cat "${SHARED}/pre-push")" "my own pre-push" "a hook of somebody else"
	assert_contains "$(cat "${SHARED}/post-rewrite")" "my own post-rewrite" "a hook of somebody else"
	assert_eq "$(find "${SHARED}" -type f | sed 's|.*/||' | sort | tr '\n' ' ')" \
		"post-applypatch post-rewrite pre-push " "what is left in the shared directory"
	cd ..

	hostile_repo hostile
	git clone -q hostile victim
	[[ ! -e PWNED ]] || fail "cloning a repository ran its harden-permissions.sh"

	# SOPS_FILTER_INSTALL_HOOKS=0 skips writing hooks, not this clean-up.
	# shellcheck disable=SC2016
	old_hook post-checkout 'HARDEN="$root/'"${TOOL}"'/harden-permissions.sh"' >"${SHARED}/post-checkout"
	cd repo || exit 1
	SOPS_FILTER_INSTALL_HOOKS=0 "${TOOL}/install.sh"
	[[ ! -e "${SHARED}/post-checkout" ]] || fail "the clean-up did not run with SOPS_FILTER_INSTALL_HOOKS=0"
}

# The line install.sh prints for a shared directory does its work in this
# repository and nothing in any other.
test_hooks_line_for_a_shared_directory_acts_in_one_repository_only() {
	umask 022
	shared_hooks_home
	plain_repo repo
	run "${TOOL}/install.sh"
	local line
	line="$(printf '%s\n' "${OUT}" | grep -F 'git rev-parse --show-toplevel 2>/dev/null' | sed 's/^ *//')"
	assert_contains "${line}" "harden-permissions.sh" "the line to add by hand"
	printf '#!/bin/sh\n%s\n' "${line}" >"${SHARED}/post-checkout"
	chmod +x "${SHARED}/post-checkout"

	printf 'A=1\n' >.env
	git add .env
	git commit -q -m "v1"
	printf 'A=2\n' >.env
	git commit -q -am "v2"
	chmod 644 .env
	git checkout -q HEAD~1
	assert_eq "$(cat .env)" "A=1" "working copy after the checkout"
	assert_eq "$(mode_of .env)" "600" "mode after the checkout, through the shared hook"
	cd ..

	hostile_repo hostile
	git clone -q hostile victim
	[[ ! -e PWNED ]] || fail "the shared hook ran the script of a cloned repository"
}

# A machine-wide hooks directory can lie INSIDE the repository that is
# being configured (a dotfiles repository that holds ~/.githooks). It is
# shared all the same.
test_hooks_machine_wide_directory_inside_the_repository_is_shared() {
	shared_hooks_home
	plain_repo repo
	mkdir hooks
	git config --global core.hooksPath "${PWD}/hooks"
	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	assert_contains "${OUT}" "not write there" "install.sh output"
	assert_eq "$(ls -A hooks)" "" "files in the machine-wide hooks directory"
}

# core.hooksPath set for this repository alone, to a directory inside it,
# is the repository's own: the hooks go there and work.
test_hooks_are_written_into_a_hooks_path_of_the_repository() {
	umask 022
	plain_repo repo
	git config --local core.hooksPath .githooks
	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	assert_contains "$(cat .githooks/post-checkout)" 'managed by sops-git-filters' "the hook in .githooks"

	printf 'A=1\n' >.env
	git add .env
	git commit -q -m "v1"
	printf 'A=2\n' >.env
	git commit -q -am "v2"
	chmod 644 .env
	git checkout -q HEAD~1
	assert_eq "$(mode_of .env)" "600" "mode after the checkout"
}

# A hook that is a symlink is never written through: its target can be a
# file that other repositories use.
test_hooks_are_not_written_through_a_symlink() {
	plain_repo repo
	mkdir -p ../elsewhere .git/hooks
	# shellcheck disable=SC2016
	old_hook post-merge 'HARDEN="$root/'"${TOOL}"'/harden-permissions.sh"' >../elsewhere/post-merge
	cp ../elsewhere/post-merge ../post-merge.before
	ln -s ../../../elsewhere/post-merge .git/hooks/post-merge

	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	cmp ../elsewhere/post-merge ../post-merge.before || fail "install.sh wrote through the symlink"
	[[ -L .git/hooks/post-merge ]] || fail "the symlink was replaced"
	assert_contains "${OUT}" "not managed by sops-git-filters: post-merge" "install.sh output"
	assert_contains "$(cat .git/hooks/post-checkout)" 'managed by sops-git-filters' "the hooks next to it"
}

# A hooks directory that is itself a symlink to a place outside the
# repository is shared too.
test_hooks_directory_symlinked_out_of_the_repository_is_shared() {
	plain_repo repo
	mkdir ../elsewhere
	if [[ -d .git/hooks ]]; then
		mv .git/hooks ../hooks-as-git-made-them
	fi
	ln -s ../../elsewhere .git/hooks
	run "${TOOL}/install.sh"
	assert_eq "${RC}" "0" "install.sh exit status"
	assert_contains "${OUT}" "not write there" "install.sh output"
	assert_eq "$(ls -A ../elsewhere)" "" "files behind the symlink"
}
